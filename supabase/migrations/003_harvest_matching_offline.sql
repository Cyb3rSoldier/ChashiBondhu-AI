-- ChashiBondhu migration 003 - Pre-harvest buyer matching + offline sync (Phase 2)
-- Run AFTER 002: Supabase Dashboard -> SQL Editor -> New query -> paste this whole file -> Run.
-- Safe to run again. One transaction: if any line fails, nothing changes.
--
-- * harvest_forecasts      a farmer's EXPECTED harvest (never stock). On harvest confirmation a normal
--                          'available' listing is created with the ACTUAL quantity -> existing marketplace/orders.
-- * buyer_demand_requests  what a buyer wants (crop, quantity, dates, area)
-- * harvest_matches        one row per forecast x request once someone shows interest (a match is NOT an order)
-- * client_id columns      offline sync idempotency: the same offline draft can never create two records
-- * trigger                when the buyer of a confirmed match orders that listing, the match becomes 'converted'

BEGIN;

CREATE TABLE IF NOT EXISTS harvest_forecasts (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farmer_id           BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  client_id           UUID,                                   -- set when created from an offline draft
  crop_id             TEXT,                                   -- crop catalogue id when known
  product_name        TEXT NOT NULL CHECK (length(product_name) BETWEEN 2 AND 120),
  variety             TEXT CHECK (length(variety) <= 80),
  expected_qty        NUMERIC(12,2) NOT NULL CHECK (expected_qty > 0),
  unit                TEXT NOT NULL CHECK (unit IN ('kg', 'gram', 'maund', 'piece', 'dozen', 'litre', 'packet')),
  harvest_from        DATE NOT NULL,
  harvest_to          DATE NOT NULL,
  district_code       TEXT CHECK (district_code ~ '^BD[0-9]{4}$'),
  upazila_code        TEXT CHECK (upazila_code ~ '^BD[0-9]{8}$'),
  description         TEXT CHECK (length(description) <= 2000),
  quality_grade       TEXT CHECK (length(quality_grade) <= 60),
  status              TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'harvest_confirmed', 'cancelled', 'expired')),
  actual_qty          NUMERIC(12,2) CHECK (actual_qty >= 0),
  actual_harvest_date DATE,
  listing_id          BIGINT REFERENCES listings(id) ON DELETE SET NULL,
  version             INT NOT NULL DEFAULT 1,                 -- conflict detection for edits
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (harvest_to >= harvest_from),
  CHECK (status <> 'harvest_confirmed' OR (actual_qty IS NOT NULL AND actual_harvest_date IS NOT NULL)),
  UNIQUE (farmer_id, client_id)
);
CREATE INDEX IF NOT EXISTS idx_forecasts_farmer ON harvest_forecasts (farmer_id, status);
CREATE INDEX IF NOT EXISTS idx_forecasts_match  ON harvest_forecasts (status, crop_id, harvest_from);
DROP TRIGGER IF EXISTS trg_forecasts_updated ON harvest_forecasts;
CREATE TRIGGER trg_forecasts_updated BEFORE UPDATE ON harvest_forecasts FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS buyer_demand_requests (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  buyer_id       BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  crop_id        TEXT,
  product_name   TEXT NOT NULL CHECK (length(product_name) BETWEEN 2 AND 120),
  variety        TEXT CHECK (length(variety) <= 80),
  quantity       NUMERIC(12,2) NOT NULL CHECK (quantity > 0),
  unit           TEXT NOT NULL CHECK (unit IN ('kg', 'gram', 'maund', 'piece', 'dozen', 'litre', 'packet')),
  needed_from    DATE NOT NULL,
  needed_to      DATE NOT NULL,
  district_code  TEXT CHECK (district_code ~ '^BD[0-9]{4}$'),
  upazila_code   TEXT CHECK (upazila_code ~ '^BD[0-9]{8}$'),
  note           TEXT CHECK (length(note) <= 1000),
  status         TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'fulfilled', 'cancelled', 'expired')),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (needed_to >= needed_from)
);
CREATE INDEX IF NOT EXISTS idx_requests_buyer ON buyer_demand_requests (buyer_id, status);
CREATE INDEX IF NOT EXISTS idx_requests_match ON buyer_demand_requests (status, crop_id, needed_from);
DROP TRIGGER IF EXISTS trg_requests_updated ON buyer_demand_requests;
CREATE TRIGGER trg_requests_updated BEFORE UPDATE ON buyer_demand_requests FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS harvest_matches (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  forecast_id    BIGINT NOT NULL REFERENCES harvest_forecasts(id) ON DELETE CASCADE,
  request_id     BIGINT NOT NULL REFERENCES buyer_demand_requests(id) ON DELETE CASCADE,
  match_qty      NUMERIC(12,2) NOT NULL CHECK (match_qty > 0),     -- interest, based on EXPECTED harvest
  confirmed_qty  NUMERIC(12,2) CHECK (confirmed_qty >= 0),         -- after the farmer confirms the real harvest
  status         TEXT NOT NULL CHECK (status IN ('buyer_interested', 'farmer_offered', 'agreed', 'declined',
                                                 'qty_confirmed', 'converted', 'cancelled', 'expired')),
  order_id       BIGINT REFERENCES orders(id) ON DELETE SET NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (forecast_id, request_id)
);
CREATE INDEX IF NOT EXISTS idx_matches_request ON harvest_matches (request_id, status);
DROP TRIGGER IF EXISTS trg_matches_updated ON harvest_matches;
CREATE TRIGGER trg_matches_updated BEFORE UPDATE ON harvest_matches FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- offline sync: product drafts carry a client-made id; the same id can only create one product
ALTER TABLE listings ADD COLUMN IF NOT EXISTS client_id UUID;
CREATE UNIQUE INDEX IF NOT EXISTS uq_listings_farmer_client ON listings (farmer_id, client_id) WHERE client_id IS NOT NULL;

-- a confirmed match becomes 'converted' when that buyer orders the listing made from the harvest
CREATE OR REPLACE FUNCTION matches_on_order_item() RETURNS trigger AS $$
BEGIN
  IF NEW.listing_id IS NULL THEN
    RETURN NEW;
  END IF;
  UPDATE harvest_matches m SET status = 'converted', order_id = NEW.order_id
  FROM harvest_forecasts f, buyer_demand_requests r, orders o
  WHERE m.forecast_id = f.id AND m.request_id = r.id AND o.id = NEW.order_id
    AND f.listing_id = NEW.listing_id AND r.buyer_id = o.customer_id AND m.status = 'qty_confirmed';
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_order_items_matches ON order_items;
CREATE TRIGGER trg_order_items_matches AFTER INSERT ON order_items FOR EACH ROW EXECUTE FUNCTION matches_on_order_item();

ALTER TABLE harvest_forecasts     ENABLE ROW LEVEL SECURITY;
ALTER TABLE buyer_demand_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE harvest_matches       ENABLE ROW LEVEL SECURITY;
INSERT INTO schema_migrations (version) VALUES ('003_harvest_matching_offline') ON CONFLICT DO NOTHING;

COMMIT;
