-- ChashiBondhu migration 002 - Farmer dashboard (Phase 1)
-- Run AFTER 001_init.sql: Supabase Dashboard -> SQL Editor -> New query -> paste this whole file -> Run.
-- Safe to run again (it only adds what is missing). Everything runs in ONE transaction:
-- if any line fails, nothing is changed.
--
-- What it adds
-- * users.avatar_path                      profile photo
-- * listings: farming_method, harvest_date, extra_info, archived_at, more categories/units,
--             status 'archived' (= soft delete; old orders keep their link to the product)
-- * order_items.stock_deducted             stock is taken only once when the farmer confirms
-- * farmer_ledger + trigger                earnings are credited only when an order is delivered AND paid;
--                                          a refund/cancel after that adds a reversal. UNIQUE rows = no double credit.
-- * complaints                             complaint box with its own number CMPYYMMDD-00001
-- * market_prices                          observed prices only, every row has a source and a date

BEGIN;

-- ---------------------------------------------------------------- users
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_path TEXT;

-- ---------------------------------------------------------------- listings
ALTER TABLE listings ADD COLUMN IF NOT EXISTS farming_method TEXT NOT NULL DEFAULT 'conventional';
ALTER TABLE listings ADD COLUMN IF NOT EXISTS harvest_date  DATE;
ALTER TABLE listings ADD COLUMN IF NOT EXISTS extra_info    TEXT;
ALTER TABLE listings ADD COLUMN IF NOT EXISTS archived_at   TIMESTAMPTZ;

-- the organic tick box becomes a farming method (old rows keep their meaning)
UPDATE listings SET farming_method = 'organic' WHERE is_organic AND farming_method = 'conventional';

ALTER TABLE listings DROP CONSTRAINT IF EXISTS listings_farming_method_check;
ALTER TABLE listings ADD  CONSTRAINT listings_farming_method_check
  CHECK (farming_method IN ('organic', 'conventional', 'other'));

-- wider category / unit / status lists (old values stay valid)
ALTER TABLE listings DROP CONSTRAINT IF EXISTS listings_category_check;
ALTER TABLE listings ADD  CONSTRAINT listings_category_check CHECK (category IN (
  'vegetable', 'fruit', 'grain', 'pulse', 'oilseed', 'spice',
  'fish', 'meat_poultry', 'dairy', 'eggs', 'seeds_inputs', 'other'));

ALTER TABLE listings DROP CONSTRAINT IF EXISTS listings_unit_check;
ALTER TABLE listings ADD  CONSTRAINT listings_unit_check CHECK (unit IN (
  'kg', 'gram', 'maund', 'piece', 'dozen', 'litre', 'packet'));

ALTER TABLE listings DROP CONSTRAINT IF EXISTS listings_status_check;
ALTER TABLE listings ADD  CONSTRAINT listings_status_check CHECK (status IN (
  'draft', 'active', 'sold_out', 'hidden', 'archived'));

-- ---------------------------------------------------------------- orders: stock taken once
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS stock_deducted BOOLEAN NOT NULL DEFAULT FALSE;
CREATE INDEX IF NOT EXISTS idx_orders_created ON orders (created_at);

-- ---------------------------------------------------------------- earnings ledger
CREATE TABLE IF NOT EXISTS farmer_ledger (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farmer_id      BIGINT NOT NULL REFERENCES users(id),
  order_item_id  BIGINT NOT NULL REFERENCES order_items(id),
  entry_type     TEXT NOT NULL CHECK (entry_type IN ('sale_credit', 'refund_reversal')),
  amount         NUMERIC(12,2) NOT NULL,          -- credit > 0, reversal < 0
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (order_item_id, entry_type),             -- one credit and at most one reversal per item
  CHECK ((entry_type = 'sale_credit' AND amount >= 0) OR (entry_type = 'refund_reversal' AND amount <= 0))
);
CREATE INDEX IF NOT EXISTS idx_ledger_farmer ON farmer_ledger (farmer_id, created_at);

CREATE OR REPLACE FUNCTION ledger_on_order_change() RETURNS trigger AS $$
BEGIN
  -- credit: order delivered AND paid -> one credit per farmer item that was not rejected
  IF NEW.status = 'delivered' AND NEW.payment_status = 'paid' THEN
    INSERT INTO farmer_ledger (farmer_id, order_item_id, entry_type, amount)
    SELECT oi.farmer_id, oi.id, 'sale_credit', oi.line_total
    FROM order_items oi
    WHERE oi.order_id = NEW.id AND oi.farmer_status <> 'rejected'
    ON CONFLICT (order_item_id, entry_type) DO NOTHING;
  END IF;
  -- reversal: refunded or cancelled after a credit
  IF NEW.payment_status = 'refunded' OR NEW.status = 'cancelled' THEN
    INSERT INTO farmer_ledger (farmer_id, order_item_id, entry_type, amount)
    SELECT l.farmer_id, l.order_item_id, 'refund_reversal', -l.amount
    FROM farmer_ledger l JOIN order_items oi ON oi.id = l.order_item_id
    WHERE oi.order_id = NEW.id AND l.entry_type = 'sale_credit'
    ON CONFLICT (order_item_id, entry_type) DO NOTHING;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_orders_ledger ON orders;
CREATE TRIGGER trg_orders_ledger AFTER UPDATE OF status, payment_status ON orders
  FOR EACH ROW EXECUTE FUNCTION ledger_on_order_change();

-- ---------------------------------------------------------------- complaints
CREATE SEQUENCE IF NOT EXISTS complaint_number_seq;
CREATE TABLE IF NOT EXISTS complaints (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  complaint_number  TEXT NOT NULL UNIQUE
                    DEFAULT ('CMP' || to_char(now() AT TIME ZONE 'Asia/Dhaka', 'YYMMDD') || '-' || lpad(nextval('complaint_number_seq')::text, 5, '0')),
  user_id           BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  category          TEXT NOT NULL CHECK (category IN ('order', 'payment', 'product', 'account', 'website', 'other')),
  subject           TEXT NOT NULL CHECK (length(subject) BETWEEN 3 AND 120),
  description       TEXT NOT NULL CHECK (length(description) BETWEEN 10 AND 3000),
  image_path        TEXT,                       -- private file name, served only to the owner
  status            TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'in_review', 'resolved', 'closed')),
  admin_response    TEXT,
  responded_by      BIGINT REFERENCES users(id) ON DELETE SET NULL,
  responded_at      TIMESTAMPTZ,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_complaints_user ON complaints (user_id, created_at DESC);
DROP TRIGGER IF EXISTS trg_complaints_updated ON complaints;
CREATE TRIGGER trg_complaints_updated BEFORE UPDATE ON complaints FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------- market prices (observed only)
CREATE TABLE IF NOT EXISTS market_prices (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_key      TEXT NOT NULL,              -- crop_id from the catalogue when possible (e.g. potato)
  product_name_bn  TEXT,
  product_name_en  TEXT,
  market_name      TEXT NOT NULL,
  district_code    TEXT CHECK (district_code ~ '^BD[0-9]{4}$'),
  unit             TEXT NOT NULL,              -- e.g. kg
  price_min        NUMERIC(10,2) CHECK (price_min >= 0),
  price_max        NUMERIC(10,2) CHECK (price_max >= 0),
  price_avg        NUMERIC(10,2) CHECK (price_avg >= 0),
  observed_at      TIMESTAMPTZ NOT NULL,
  source_name      TEXT NOT NULL,
  source_url       TEXT,
  imported_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (price_min IS NULL OR price_max IS NULL OR price_min <= price_max),
  CHECK (coalesce(price_min, price_max, price_avg) IS NOT NULL),
  UNIQUE (product_key, market_name, observed_at, source_name)
);
CREATE INDEX IF NOT EXISTS idx_prices_product ON market_prices (product_key, observed_at DESC);

-- ---------------------------------------------------------------- security + version
ALTER TABLE farmer_ledger ENABLE ROW LEVEL SECURITY;
ALTER TABLE complaints    ENABLE ROW LEVEL SECURITY;
ALTER TABLE market_prices ENABLE ROW LEVEL SECURITY;
INSERT INTO schema_migrations (version) VALUES ('002_farmer_dashboard') ON CONFLICT DO NOTHING;

COMMIT;
