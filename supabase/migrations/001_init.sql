-- Safe to run again: it only creates what is missing.
--
-- Design notes
-- * One "users" table for farmers, customers and admins (role column), login by phone number.
-- * Area codes are our HDX COD-AB codes (division BD20, district BD2019, upazila BD20190009).
-- * crop_id values come from data/reference/crop_catalogue.csv (e.g. potato, aman_rice).
-- * Expected harvest and available stock are kept apart (listing_type), never mixed.
-- * Photos sent to the AI are NOT stored; only the result is kept.
-- * No NID numbers are stored (privacy).

-- ---------------------------------------------------------------- helpers
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------- users
CREATE TABLE IF NOT EXISTS users (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role            TEXT NOT NULL CHECK (role IN ('farmer', 'customer', 'admin')),
  full_name       TEXT NOT NULL CHECK (length(full_name) BETWEEN 2 AND 100),
  phone           TEXT NOT NULL UNIQUE CHECK (phone ~ '^\+8801[3-9][0-9]{8}$'),  -- stored as +8801XXXXXXXXX
  email           TEXT UNIQUE,
  password_hash   TEXT NOT NULL,
  district_code   TEXT CHECK (district_code ~ '^BD[0-9]{4}$'),
  upazila_code    TEXT CHECK (upazila_code ~ '^BD[0-9]{8}$'),
  address         TEXT,
  status          TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('pending', 'active', 'suspended')),
  preferred_lang  TEXT NOT NULL DEFAULT 'bn' CHECK (preferred_lang IN ('bn', 'en')),
  failed_logins   INT NOT NULL DEFAULT 0,
  locked_until    TIMESTAMPTZ,
  last_login_at   TIMESTAMPTZ,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_users_role     ON users (role);
CREATE INDEX IF NOT EXISTS idx_users_district ON users (district_code);
DROP TRIGGER IF EXISTS trg_users_updated ON users;
CREATE TRIGGER trg_users_updated BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------- farmer profile + farm
CREATE TABLE IF NOT EXISTS farmer_profiles (
  user_id          BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  land_decimal     NUMERIC(10,2) CHECK (land_decimal >= 0),   -- total land in decimal (shotangsho)
  land_text        TEXT,                                      -- as the farmer said it, e.g. "২ বিঘা"
  main_crops       TEXT[] NOT NULL DEFAULT '{}',              -- crop_id list
  has_irrigation   BOOLEAN,
  verified_at      TIMESTAMPTZ,                               -- set by admin
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
DROP TRIGGER IF EXISTS trg_farmer_profiles_updated ON farmer_profiles;
CREATE TRIGGER trg_farmer_profiles_updated BEFORE UPDATE ON farmer_profiles FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- A farmer's plots of land ("My farm")
CREATE TABLE IF NOT EXISTS farm_plots (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farmer_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name           TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
  area_decimal   NUMERIC(10,2) CHECK (area_decimal > 0),
  upazila_code   TEXT CHECK (upazila_code ~ '^BD[0-9]{8}$'),
  land_type      TEXT CHECK (land_type IN ('high', 'medium_high', 'medium_low', 'low', 'very_low')),
  irrigation     BOOLEAN,
  notes          TEXT,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_plots_farmer ON farm_plots (farmer_id);
DROP TRIGGER IF EXISTS trg_plots_updated ON farm_plots;
CREATE TRIGGER trg_plots_updated BEFORE UPDATE ON farm_plots FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- What is planted on a plot, and when
CREATE TABLE IF NOT EXISTS plantings (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plot_id             BIGINT NOT NULL REFERENCES farm_plots(id) ON DELETE CASCADE,
  farmer_id           BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  crop_id             TEXT NOT NULL,
  variety             TEXT,
  season              TEXT CHECK (season IN ('rabi', 'kharif1', 'kharif2')),
  planted_on          DATE,
  expected_harvest_on DATE,
  harvested_on        DATE,
  status              TEXT NOT NULL DEFAULT 'growing' CHECK (status IN ('planned', 'growing', 'harvested', 'failed')),
  notes               TEXT,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_plantings_farmer ON plantings (farmer_id);
DROP TRIGGER IF EXISTS trg_plantings_updated ON plantings;
CREATE TRIGGER trg_plantings_updated BEFORE UPDATE ON plantings FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------- marketplace
CREATE TABLE IF NOT EXISTS listings (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farmer_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  listing_type     TEXT NOT NULL DEFAULT 'available' CHECK (listing_type IN ('available', 'expected')),
  crop_id          TEXT,                                  -- from the crop catalogue (optional)
  title            TEXT NOT NULL CHECK (length(title) BETWEEN 2 AND 120),
  category         TEXT NOT NULL DEFAULT 'other' CHECK (category IN ('grain', 'vegetable', 'fruit', 'pulse', 'oilseed', 'spice', 'other')),
  description      TEXT,
  unit             TEXT NOT NULL CHECK (unit IN ('kg', 'maund', 'piece', 'dozen', 'litre')),
  price_per_unit   NUMERIC(10,2) NOT NULL CHECK (price_per_unit > 0),  -- set by the farmer
  quantity         NUMERIC(12,2) NOT NULL CHECK (quantity >= 0),
  min_order        NUMERIC(12,2) NOT NULL DEFAULT 1 CHECK (min_order > 0),
  is_organic       BOOLEAN NOT NULL DEFAULT FALSE,
  image_path       TEXT,
  available_from   DATE,                                  -- for 'expected': expected harvest date
  district_code    TEXT CHECK (district_code ~ '^BD[0-9]{4}$'),
  upazila_code     TEXT CHECK (upazila_code ~ '^BD[0-9]{8}$'),
  status           TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('draft', 'active', 'sold_out', 'hidden')),
  views            INT NOT NULL DEFAULT 0,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (listing_type = 'available' OR available_from IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_listings_farmer   ON listings (farmer_id);
CREATE INDEX IF NOT EXISTS idx_listings_status   ON listings (status, listing_type);
CREATE INDEX IF NOT EXISTS idx_listings_crop     ON listings (crop_id);
CREATE INDEX IF NOT EXISTS idx_listings_district ON listings (district_code);
DROP TRIGGER IF EXISTS trg_listings_updated ON listings;
CREATE TRIGGER trg_listings_updated BEFORE UPDATE ON listings FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS cart_items (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  listing_id  BIGINT NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  quantity    NUMERIC(12,2) NOT NULL CHECK (quantity > 0),
  added_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (customer_id, listing_id)
);

CREATE SEQUENCE IF NOT EXISTS order_number_seq;
CREATE TABLE IF NOT EXISTS orders (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number     TEXT NOT NULL UNIQUE
                   DEFAULT ('CB' || to_char(now() AT TIME ZONE 'Asia/Dhaka', 'YYMMDD') || '-' || lpad(nextval('order_number_seq')::text, 5, '0')),
  customer_id      BIGINT NOT NULL REFERENCES users(id),
  status           TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'shipped', 'delivered', 'cancelled')),
  payment_method   TEXT NOT NULL DEFAULT 'cod' CHECK (payment_method IN ('cod')),
  payment_status   TEXT NOT NULL DEFAULT 'unpaid' CHECK (payment_status IN ('unpaid', 'paid', 'refunded')),
  subtotal         NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
  delivery_fee     NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
  total            NUMERIC(12,2) NOT NULL CHECK (total >= 0),
  delivery_address TEXT NOT NULL,
  phone            TEXT NOT NULL,
  note             TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_orders_customer ON orders (customer_id);
CREATE INDEX IF NOT EXISTS idx_orders_status   ON orders (status);
DROP TRIGGER IF EXISTS trg_orders_updated ON orders;
CREATE TRIGGER trg_orders_updated BEFORE UPDATE ON orders FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS order_items (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id       BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  listing_id     BIGINT REFERENCES listings(id) ON DELETE SET NULL,
  farmer_id      BIGINT NOT NULL REFERENCES users(id),
  title          TEXT NOT NULL,              -- copy at order time
  unit           TEXT NOT NULL,
  unit_price     NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
  quantity       NUMERIC(12,2) NOT NULL CHECK (quantity > 0),
  line_total     NUMERIC(12,2) NOT NULL CHECK (line_total >= 0),
  farmer_status  TEXT NOT NULL DEFAULT 'pending' CHECK (farmer_status IN ('pending', 'accepted', 'packed', 'handed_over', 'rejected'))
);
CREATE INDEX IF NOT EXISTS idx_order_items_order  ON order_items (order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_farmer ON order_items (farmer_id);

CREATE TABLE IF NOT EXISTS reviews (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id  BIGINT NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  customer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  rating      SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment     TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (listing_id, customer_id)
);

-- ---------------------------------------------------------------- AI assistant history
CREATE TABLE IF NOT EXISTS ai_conversations (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT REFERENCES users(id) ON DELETE CASCADE,   -- NULL = guest
  title       TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_ai_conv_user ON ai_conversations (user_id, updated_at DESC);
DROP TRIGGER IF EXISTS trg_ai_conv_updated ON ai_conversations;
CREATE TRIGGER trg_ai_conv_updated BEFORE UPDATE ON ai_conversations FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS ai_messages (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT NOT NULL REFERENCES ai_conversations(id) ON DELETE CASCADE,
  role            TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
  kind            TEXT NOT NULL DEFAULT 'text' CHECK (kind IN ('text', 'photo')),
  content         TEXT NOT NULL,
  status          TEXT,          -- assistant status: verified, possible, unsure, ...
  crop_id         TEXT,          -- for photo checks
  sources         JSONB,         -- book pages used
  candidates      JSONB,         -- photo check candidates
  model           TEXT,          -- which model answered (groq / gemma ...)
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_ai_msg_conv ON ai_messages (conversation_id, created_at);

CREATE TABLE IF NOT EXISTS ai_feedback (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id  BIGINT NOT NULL REFERENCES ai_messages(id) ON DELETE CASCADE,
  user_id     BIGINT REFERENCES users(id) ON DELETE SET NULL,
  helpful     BOOLEAN NOT NULL,
  comment     TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (message_id, user_id)
);

-- ---------------------------------------------------------------- admin / communication
CREATE TABLE IF NOT EXISTS notifications (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title       TEXT NOT NULL,
  body        TEXT,
  link        TEXT,
  read_at     TIMESTAMPTZ,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications (user_id, read_at);

CREATE TABLE IF NOT EXISTS announcements (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       TEXT NOT NULL,
  body        TEXT NOT NULL,
  audience    TEXT NOT NULL DEFAULT 'all' CHECK (audience IN ('all', 'farmer', 'customer')),
  created_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS contact_messages (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL,
  phone       TEXT,
  email       TEXT,
  subject     TEXT NOT NULL,
  message     TEXT NOT NULL,
  handled     BOOLEAN NOT NULL DEFAULT FALSE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

